// Regenerate src/client/prices.gen.ts from models.dev.
//
// The plugin ships a snapshot of the DeepSeek list prices instead of fetching
// models.dev from the browser: the renderer would take a cross-origin request on
// every page load, and a provider outage must not be able to break a notice line.
// Run `pnpm run prices` and commit the result when the catalog changes.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const SOURCE = 'https://models.dev/api.json'
const PROVIDER = 'deepseek'
const TARGET = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'client', 'prices.gen.ts')

const response = await fetch(SOURCE)
if (!response.ok) throw new Error(`models.dev returned ${response.status}`)
const catalog = await response.json()
const provider = catalog?.[PROVIDER]
if (provider === undefined || typeof provider !== 'object') throw new Error(`models.dev has no "${PROVIDER}" provider`)

const normalize = (model) => ({
  input: model?.cost?.input,
  cacheRead: model?.cost?.cache_read ?? 0,
  output: model?.cost?.output,
})

const rows = []
for (const [id, model] of Object.entries(provider.models ?? {})) {
  const price = normalize(model)
  for (const key of ['input', 'output', 'cacheRead']) {
    if (typeof price[key] !== 'number' || !Number.isFinite(price[key])) {
      throw new Error(`models.dev model "${id}" has no numeric ${key} price`)
    }
  }
  // Keep models.dev's own identifiers verbatim; old providers still report old ids.
  rows.push([id, price])
}
rows.sort(([left], [right]) => left.localeCompare(right))

const body = rows
  .map(([id, price]) => `  '${id}': { input: ${price.input}, cacheRead: ${price.cacheRead}, output: ${price.output} },`)
  .join('\n')

const file = `// Generated by scripts/fetch-prices.mjs — do not edit by hand.
// Source: ${SOURCE} (provider "${PROVIDER}"), snapshot ${new Date().toISOString().slice(0, 10)}.
// Prices are USD per 1M tokens, exactly as models.dev publishes them.

/** Catalog the snapshot was taken from. */
export const PRICE_SOURCE = '${SOURCE}'

/** Snapshot date (UTC, day precision). */
export const PRICE_SNAPSHOT = '${new Date().toISOString().slice(0, 10)}'

/** One model's list prices, USD per 1M tokens. */
export interface ModelPrice {
  /** Uncached prompt input. */
  readonly input: number
  /** Cache-hit prompt input. */
  readonly cacheRead: number
  /** Completion output. */
  readonly output: number
}

/** List prices keyed by the model id the provider reports. */
export const MODEL_PRICES: Readonly<Record<string, ModelPrice>> = {
${body}
}
`

writeFileSync(TARGET, file, 'utf8')
console.log(`wrote ${TARGET} (${rows.length} models from ${PROVIDER})`)
